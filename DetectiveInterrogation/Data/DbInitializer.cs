        void UpsertAchievement(string oldTitle, string title, string description)
        {
            var achievement = context.Achievements.FirstOrDefault(a => a.Title == title)
                ?? context.Achievements.FirstOrDefault(a => a.Title == oldTitle);

            if (achievement == null)
            {
                context.Achievements.Add(new Achievement { Title = title, Description = description });
                return;
            }

            achievement.Title = title;
            achievement.Description = description;
        }

        void ResetEvidenceData(int caseId)
        {
            var phraseIds = context.EvidencePhrases
                .Where(p => p.Evidence.CaseId == caseId)
                .Select(p => p.Id)
                .ToList();

            context.SuspectReplies.RemoveRange(context.SuspectReplies.Where(r => phraseIds.Contains(r.EvidencePhraseId)));
            context.EvidencePhrases.RemoveRange(context.EvidencePhrases.Where(p => p.Evidence.CaseId == caseId));
            context.SessionUsedEvidences.RemoveRange(context.SessionUsedEvidences.Where(sue => sue.Evidence.CaseId == caseId));
            context.Evidence.RemoveRange(context.Evidence.Where(e => e.CaseId == caseId));
            context.SaveChanges();
        }

